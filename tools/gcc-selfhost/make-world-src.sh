#!/usr/bin/env bash
# Phase 7 P7.3: the source tarball for "the stage3 gcc rebuilds the userland".
#
# InstantOS has no cmake/ninja (or meson/python), so the build systems run here
# once, for the GCC cross (tools/build-userland-gcc.sh), and this script turns
# their exact command lines into plain shell scripts the in-OS gcc runs:
#
#   /world/src/InstantOS/...     the sources those commands read
#   /world/build-userland.sh     iUserApps: ld-instantos.so, libinstant.so, the
#                                managers and apps (ninja -t commands, rewritten)
#   /world/build-suite.sh        the feature suite's runner and ostest-helper
#                                (build-testsuite-iso.sh's compile_freestanding)
#   /world/build-mlibc.sh        mlibc (meson's commands, rewritten) and its
#                                install into /world/mlibc-root
#   /world/build-ports.sh        bash and tinycc through tools/build-bash.sh and
#                                build-tcc.sh (their own configure + make), on
#                                the in-OS mlibc and a tcc sysroot made from
#                                the in-OS userland
#
# Every compile and link happens in-OS: the scripts only name the compiler
# (`g++`/`gcc`, the stage3 compiler once launcher-world.c has installed it) and
# `ld`. Output: build/p73/world-src.tar.gz, which make-world-disk / debugfs puts
# at /src/world-src.tar.gz on the P7.2 disk.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
BUILD_DIR="${BUILD_DIR:-$ROOT/build}"
OUT_DIR="${OUT_DIR:-$BUILD_DIR/p73}"
UA_BUILD="${USERLAND_GCC_BUILD_DIR:-$BUILD_DIR/iUserApps-gcc}"
GCC_PREFIX="${GCC_PORT_DIR:-$HOME/gcc-port}/gcc-install/bin/x86_64-unknown-instantos-"
W=/world/src/InstantOS   # where $ROOT's files live in-OS

[ -f "$UA_BUILD/build.ninja" ] || { echo "run tools/build-userland-gcc.sh first" >&2; exit 2; }

STAGE="$OUT_DIR/stage"
rm -rf "$STAGE"; mkdir -p "$STAGE/world/src/InstantOS/tools/os-testsuite"

# --- sources -----------------------------------------------------------------
# The kernel headers (iUserApps includes syscall.hpp and friends from include/),
# iUserApps without mlibc/tinycc (added below) and without git metadata, the suite.
tar -C "$ROOT" -cf - include | tar -C "$STAGE/world/src/InstantOS" -xf -
tar -C "$ROOT" --exclude=.git --exclude='outside/iUserApps/outside/mlibc' \
    --exclude='outside/iUserApps/outside/tinycc' -cf - outside/iUserApps \
  | tar -C "$STAGE/world/src/InstantOS" -xf -
cp "$ROOT"/tools/os-testsuite/*.c "$ROOT"/tools/os-testsuite/*.h "$STAGE/world/src/InstantOS/tools/os-testsuite/"

# --- iUserApps: ninja's commands as a shell script -----------------------------
# Rewrites: the cross compiler -> the native one on PATH, the cross linker -> ld,
# $ROOT -> $W. Paths relative to the build directory stay relative: the script
# runs in /world/iUserApps-build.
CMDS="$OUT_DIR/userland.cmds"
ninja -C "$UA_BUILD" -t commands > "$CMDS"
{
  echo '#!/bin/sh'
  echo '# Generated by tools/gcc-selfhost/make-world-src.sh from the GCC cross build of'
  echo '# outside/iUserApps (ninja -t commands). Runs in /world/iUserApps-build.'
  echo 'set -e'
  echo 'mkdir -p /world/iUserApps-build && cd /world/iUserApps-build'
  # Every directory an output goes to.
  grep -o ' -o [^ ]*' "$CMDS" | awk '{print $2}' | xargs -n1 dirname | sort -u \
    | sed 's|^|mkdir -p |'
  n=0; total=$(wc -l < "$CMDS")
  while IFS= read -r line; do
    n=$((n+1))
    line="${line//${GCC_PREFIX}g++/g++}"
    line="${line//${GCC_PREFIX}gcc/gcc}"
    line="${line//x86_64-unknown-instantos-ld /ld }"
    line="${line//$ROOT/$W}"
    echo "echo \"[world] userland $n/$total\""
    echo "$line"
  done < "$CMDS"
} > "$STAGE/world/build-userland.sh"
if grep -q -e "$ROOT" -e "$GCC_PREFIX" -e 'instantos-ld' "$STAGE/world/build-userland.sh"; then
  echo "unrewritten host path left in build-userland.sh:" >&2
  grep -n -e "$ROOT" -e "$GCC_PREFIX" -e 'instantos-ld' "$STAGE/world/build-userland.sh" | head >&2
  exit 1
fi

# --- the suite's programs (compile_freestanding of build-testsuite-iso.sh) -----
cat > "$STAGE/world/build-suite.sh" <<EOF
#!/bin/sh
# Generated by tools/gcc-selfhost/make-world-src.sh: tools/os-testsuite's runner
# and ostest-helper, as build-testsuite-iso-gcc.sh compiles them.
set -e
mkdir -p /world/suite && cd /world/suite
INC=\$(gcc -print-file-name=include)
for p in runner:runner ostest-helper:helper; do
  out=\${p%%:*}; src=$W/tools/os-testsuite/\${p#*:}.c
  echo "[world] suite \$out"
  gcc -ffreestanding -fPIE -fno-stack-protector -nostdinc -O1 -isystem "\$INC" -c "\$src" -o "\$out.o"
  ld --gc-sections --build-id=none --hash-style=sysv -z max-page-size=0x1000 \\
    -pie -e _start --dynamic-linker /lib/ld-instantos.so -o "\$out" "\$out.o"
done
EOF

# --- M2: mlibc, bash, tinycc -----------------------------------------------------
# mlibc: meson's commands, run in a copy of its build directory (the commands
# use paths relative to it, ../../outside/...) that holds only the headers meson
# generated there (mlibc-config.h, internal-config.h); then meson's install
# manifest as cp commands into /world/mlibc-root.
ML_BUILD="${MLIBC_GCC_BUILD_DIR:-$BUILD_DIR/mlibc-build-gcc}"
ML_ROOT="${MLIBC_GCC_ROOT:-$BUILD_DIR/mlibc-root-gcc}"
BINU="$BUILD_DIR/binutils-cross/bin/x86_64-unknown-instantos-"
BASH_SRC="${BASH_SRC:-$BUILD_DIR/bash-port/bash-5.2.21}"
ML_REL="${ML_BUILD#$ROOT/}"
[ -f "$ML_BUILD/build.ninja" ] || { echo "run tools/build-mlibc-gcc.sh first" >&2; exit 2; }
[ -f "$BASH_SRC/configure" ] || { echo "missing $BASH_SRC (tools/build-bash.sh fetches it)" >&2; exit 2; }
# Symlinks are packed as the files they point to (-h): extracting a symlink as
# root makes GNU tar set its mode through gnulib's fchmodat, which opens the
# link with O_PATH|O_NOFOLLOW, and InstantOS cannot open a symlink itself yet
# (tar exits 2: "Cannot change mode to rwxrwxrwx"). mlibc's sysdeps are mostly
# such links into abis/, so only the two this build uses go in.
ML_SRC=outside/iUserApps/outside/mlibc
ML_TOP=$(cd "$ROOT/$ML_SRC" && ls -A | grep -v -x -e .git -e sysdeps | sed "s|^|$ML_SRC/|")
tar -C "$ROOT" --exclude=.git -chf - $ML_TOP "$ML_SRC/sysdeps/instantos" "$ML_SRC/sysdeps/generic-helpers" \
    outside/iUserApps/outside/tinycc | tar -C "$STAGE/world/src/InstantOS" -xf -
mkdir -p "$STAGE/world/src/InstantOS/$ML_REL" "$STAGE/world/src/InstantOS/tools/tcc" "$STAGE/world/bash-port"
(cd "$ML_BUILD" && find . -name '*.h' -print0 | tar --null -T - -cf -) | tar -C "$STAGE/world/src/InstantOS/$ML_REL" -xf -
cp "$ROOT/tools/build-bash.sh" "$ROOT/tools/build-tcc.sh" "$STAGE/world/src/InstantOS/tools/"
cp "$ROOT/tools/tcc/empty-crt.c" "$STAGE/world/src/InstantOS/tools/tcc/"
tar -C "$(dirname "$BASH_SRC")" -cf - "$(basename "$BASH_SRC")" | tar -C "$STAGE/world/bash-port" -xf -

ML_CMDS="$OUT_DIR/mlibc.cmds"
ninja -C "$ML_BUILD" -t commands | grep -v -e '--internal symbolextractor' > "$ML_CMDS"
{
  echo '#!/bin/sh'
  echo '# Generated by tools/gcc-selfhost/make-world-src.sh from the GCC cross build of'
  echo '# mlibc (ninja -t commands, without meson'"'"'s relink-avoiding symbol extractor).'
  echo 'set -e'
  echo "cd $W/$ML_REL"
  grep -o ' -o [^ ]*' "$ML_CMDS" | awk '{print $2}' | xargs -n1 dirname | sort -u | sed 's|^|mkdir -p |'
  n=0; total=$(wc -l < "$ML_CMDS")
  while IFS= read -r line; do
    n=$((n+1))
    line="${line//${GCC_PREFIX}g++/g++}"
    line="${line//${GCC_PREFIX}gcc/gcc}"
    line="${line//${BINU}ar/ar}"
    line="${line//$ROOT/$W}"
    echo "echo \"[world] mlibc $n/$total\""
    echo "$line"
  done < "$ML_CMDS"
  echo '# meson install'
  meson introspect --installed "$ML_BUILD" | python3 -c '
import json, sys, os
root, w, mlroot = sys.argv[1:4]
for src, dst in json.load(sys.stdin).items():
    src = src.replace(root, w); dst = dst.replace(mlroot, "/world/mlibc-root")
    print("mkdir -p %s && cp %s %s" % (os.path.dirname(dst), src, dst))
' "$ROOT" "$W" "$ML_ROOT"
} > "$STAGE/world/build-mlibc.sh"
if grep -q -e "$ROOT" -e "$GCC_PREFIX" -e 'instantos-ar' "$STAGE/world/build-mlibc.sh"; then
  echo "unrewritten host path left in build-mlibc.sh:" >&2
  grep -n -e "$ROOT" -e "$GCC_PREFIX" -e 'instantos-ar' "$STAGE/world/build-mlibc.sh" | head >&2
  exit 1
fi

# bash and tinycc: their own configure + make, through the same port scripts
# and flags as the cross builds (build-bash-gcc.sh, build-tcc-gcc.sh), with the
# in-OS gcc, the in-OS-built mlibc, and a tcc sysroot assembled from the in-OS
# userland as build-tcc-sysroot.sh assembles it from the clang one.
cat > "$STAGE/world/build-ports.sh" <<EOF
#!/bin/sh
# Generated by tools/gcc-selfhost/make-world-src.sh: bash and tinycc, in-OS.
set -e
# The port scripts' wrappers start with #!/usr/bin/env bash, as on Linux.
[ -e /usr/bin/env ] || cp /bin/env /usr/bin/env
GCC_INC=\$(gcc -print-file-name=include)
M=/world/mlibc-root
mkdir -p /world/out

echo "[world] bash"
WORK_DIR=/world/bash-port OUTPUT=/world/out/bash CC=gcc MLIBC_ROOT=\$M \\
LLVM_STRIP=strip LLVM_NM=nm \\
TARGET_CFLAGS="-ffreestanding -fPIE -fno-stack-protector -nostdinc -isystem \$M/include -isystem \$GCC_INC -D_GNU_SOURCE -Wno-implicit-function-declaration -fcommon" \\
TARGET_LDFLAGS="-pie -nostdlib -L\$M/lib -Wl,--dynamic-linker,/lib/mlibc/ld-instantos.so -Wl,-rpath,/lib/mlibc -Wl,--allow-multiple-definition \$M/lib/crt1.o" \\
  bash $W/tools/build-bash.sh

echo "[world] tcc sysroot"
S=/world/tcc-sysroot; U=/world/iUserApps-build
rm -rf \$S && mkdir -p \$S/include \$S/lib
cp -R $W/outside/iUserApps/outside/ilibcxx/include/. \$S/include/
cp \$U/outside/ilibcxx/CMakeFiles/instant_c_crt0.dir/src/c_runtime.cpp.o \$S/lib/crt0.o
ln -sf crt0.o \$S/lib/crt1.o && ln -sf crt0.o \$S/lib/Scrt1.o
gcc -ffreestanding -fPIC -D__INSTANT_CRT_SYM=__instant_tcc_crti -c $W/tools/tcc/empty-crt.c -o \$S/lib/crti.o
gcc -ffreestanding -fPIC -D__INSTANT_CRT_SYM=__instant_tcc_crtn -c $W/tools/tcc/empty-crt.c -o \$S/lib/crtn.o
cp \$U/libinstant.so \$S/lib/libinstant.so && ln -sf libinstant.so \$S/lib/libc.so
cp \$U/out/ld-instantos.so \$S/lib/ld-instantos.so

echo "[world] tcc"
TCC_SOURCE_DIR=$W/outside/iUserApps/outside/tinycc TCC_BUILD_DIR=/world/tcc-build \\
TCC_OUTPUT=/world/out/tcc TCC_SYSROOT=\$S TCC_SKIP_SYSROOT=1 TCC_NATIVE_BUILD=1 \\
CC=gcc AR=ar STRIP=strip \\
TCC_WRAP_CFLAGS="-fPIC -ffreestanding -fno-stack-protector -nostdinc -isystem \$S/include -isystem \$GCC_INC" \\
TCC_WRAP_LDFLAGS="-nostdlib -Wl,--gc-sections -Wl,--build-id=none -Wl,--hash-style=sysv -Wl,-z,max-page-size=0x1000 -pie -Wl,-e,_start -Wl,--dynamic-linker,/lib/ld-instantos.so" \\
TCC_WRAP_DROP_LIBS="-lm -ldl" \\
  bash $W/tools/build-tcc.sh
EOF

tar -C "$STAGE" -czf "$OUT_DIR/world-src.tar.gz" world
echo "P73_WORLD_SRC=$OUT_DIR/world-src.tar.gz ($(du -h "$OUT_DIR/world-src.tar.gz" | cut -f1), $(wc -l < "$CMDS") userland commands)"
